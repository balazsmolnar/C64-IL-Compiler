#!/usr/bin/env python3
"""
The closing slide's count-up digits as bitmap tiles (slide 16, BYTES FREE):
the title face's 0-9 drawn 2x2 like font_TitleBig, each centred in a slot
3 cells wide and 4 high, written as 12 tiles of 8 bytes per digit, row by
row, for C64.Screen.DrawTiles(column, row, 3, 4, tiles_BigDigits, digit * 12).

DrawTiles only copies bytes, so swapping a digit never shows it half drawn
(DrawFontText at 2x takes most of a frame per glyph).

    python C64Presentation/art/digits/make_digits.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
sys.path.insert(0, os.path.join(ROOT, "tools"))
import c64font  # noqa: E402

SLOT_CELLS = 3
SLOT_ROWS = 4
SCALE = 2


def digit_tiles(glyph):
    width = SLOT_CELLS * 8
    pixels = [[0] * width for _ in range(SLOT_ROWS * 8)]
    left = (width - SCALE * len(glyph[0])) // 2
    for y, row in enumerate(glyph):
        for x, bit in enumerate(row):
            if bit == "#":
                for dy in range(SCALE):
                    for dx in range(SCALE):
                        pixels[y * SCALE + dy][left + x * SCALE + dx] = 1
    tiles = []
    for cell_row in range(SLOT_ROWS):
        for cell in range(SLOT_CELLS):
            for line in range(8):
                bits = pixels[cell_row * 8 + line][cell * 8:cell * 8 + 8]
                tiles.append(sum(b << (7 - i) for i, b in enumerate(bits)))
    return tiles


def main():
    font = c64font.load(os.path.join(HERE, "..", "font", "title.txt"))
    out = ["; generated by art/digits/make_digits.py -- do not edit",
           f"; 0-9 of the title face at 2x, {SLOT_CELLS}x{SLOT_ROWS} cells each, tiles row by row",
           "tiles_BigDigits"]
    for d in "0123456789":
        tiles = digit_tiles(font.glyphs[d])
        for i in range(0, len(tiles), 24):
            out.append("    .byte " + ", ".join(f"${b:02x}" for b in tiles[i:i + 24]))
    path = os.path.join(HERE, "..", "build", "big_digits.asm")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{path}: {10 * SLOT_CELLS * SLOT_ROWS * 8} bytes")


if __name__ == "__main__":
    main()
