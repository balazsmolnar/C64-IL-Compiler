#!/usr/bin/env python3
"""
Writes Hunchback/GameData.asm from the disassembly of the original game:

    python Hunchback/tools/gamedata.py [C:/temp/HunchBack/Restructure]

Takes the text and data tables of Restructure/Memory.asm (CBM prg Studio
syntax) and the title picture (hbtitles.bin) and writes them as 64tass
.byte lines under the same labels, so the C# code can refer to the tables by
the names the disassembly uses. Text becomes screen codes. Tables that hold
addresses of the original's code or its sprite pointer values are left out
(SKIP): the port has its own.
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else r"C:\temp\HunchBack\Restructure"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "GameData.asm")

SKIP = {
    "tbl_LevelCharBlockLo", "tbl_LevelCharBlockHi",             # addresses of code
    "tbl_QuasiLeftJumpFrame", "tbl_QuasiWalkRightFrame", "tbl_QuasiWalkFrame", "tbl_QuasiJumpFrames",
    "tbl_RopeUpperFrame", "tbl_RopeLowerFrame", "tbl_HeartAnimFrames",      # sprite pointers
    "tbl_ScreenPointers", "tbl_ScreenScrollPtrs",               # screen addresses
    "tbl_KeyboardMatrixCol", "tbl_KeyMatrixColOffset", "tbl_KeyboardMatrixRow", "tbl_KeyToJoyMap",
}
# parsed (other tables are made from them) but not written
DERIVED_ONLY = {"tbl_IntroTuneFreqLo", "tbl_IntroTuneFreqHi"}
CONSTANTS = {
    "BLUE": 6, "CYAN": 3, "YELLOW": 7, "RED": 2, "PURPLE": 4,
    "CHAR_BELL_LR": 66, "CHAR_BELL_LL": 65, "CHAR_BELL_UR": 64, "CHAR_BELL_UL": 63,
}


def screen_codes(text):
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == "{":
            j = text.index("}", i)
            body = text[i + 1:j]
            if "*" in body:
                code, count = body.split("*")
                out += [int(code)] * int(count)
            else:
                out.append(int(body))
            i = j + 1
            continue
        if "a" <= ch <= "z":
            out.append(ord(ch) - 96)
        elif ch == "@":
            out.append(0)
        else:
            out.append(ord(ch))
        i += 1
    return out


def value(token):
    token = token.strip()
    if token in CONSTANTS:
        return CONSTANTS[token]
    if token.startswith("$"):
        return int(token[1:], 16)
    return int(token)


def main():
    tables = []         # (label, bytes)
    current = None
    started = False
    for line in open(os.path.join(SRC, "Memory.asm"), encoding="latin-1"):
        line = line.rstrip("\n")
        if line.startswith("*=$2A00"):
            started = True
            continue
        if not started:
            continue
        if line.startswith("tbl_HiScores"):
            break
        code = line.split(";")[0] if "'" not in line else line
        m = re.match(r"^(\w+)?\s+(byte|text|incbin)\s+(.*)$", code)
        if not m:
            m2 = re.match(r"^(\w+)\s*$", code)
            if m2:
                current = [m2.group(1), []]
                tables.append(current)
            continue
        label, kind, rest = m.groups()
        if label:
            current = [label, []]
            tables.append(current)
        if current[0] in SKIP:
            continue
        if kind == "byte":
            current[1] += [value(t) for t in rest.split(",") if t.strip()]
        elif kind == "text":
            current[1] += screen_codes(re.match(r"'(.*)'", rest.strip()).group(1))
        else:
            current[1] += list(open(os.path.join(SRC, "hbtitles.bin"), "rb").read())

    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("; GENERATED by Hunchback/tools/gamedata.py from the original game's\n")
        f.write("; disassembly (Restructure/Memory.asm, hbtitles.bin) -- do not edit.\n\n")
        f.write("screenMemory = $400\ncolorMemory = $D800\n\n")
        f.write("; A whole screen built out of sight (Screen.cs): characters, then colours.\n")
        f.write("tmpScreen .fill 1000\ntmpColour .fill 1000\n\n")
        f.write("; The hi-score table: five entries of seven score digits and three letters.\n")
        f.write("tbl_HiScores .fill 50\n\n")
        total = 0
        for label, data in tables:
            if label in SKIP or label in DERIVED_ONLY:
                continue
            f.write(label + "\n")
            for i in range(0, len(data), 16):
                f.write("    .byte " + ", ".join("$%02x" % b for b in data[i:i + 16]) + "\n")
            total += len(data)
        by_label = dict((label, data) for label, data in tables)
        f.write("\n; the intro tune's 64 notes as SID frequency values (the two tables above, as words)\n")
        notes = zip(by_label["tbl_IntroTuneFreqLo"], by_label["tbl_IntroTuneFreqHi"])
        f.write("tbl_IntroTuneFreq .word " + ", ".join("$%04x" % (lo + 256 * hi) for lo, hi in notes) + "\n")
        f.write("\n; row * 40, for each of the 25 rows (Screen.Put)\n")
        f.write("tbl_RowOffset .word " + ", ".join(str(r * 40) for r in range(25)) + "\n")
        f.write("\n; the title picture, by the name the port's code has always used\n")
        f.write("titleScreen = txt_TitleScreen\n")
    print("%d tables, %d bytes -> %s" % (len(tables), total, os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
