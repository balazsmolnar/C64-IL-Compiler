; ===========================================================================
; C64.Music (C64Lib/Music.cs) -- a small data-driven SID music + sound
; effect player.
;
; Three music voices driven by order lists -> patterns -> instruments ->
; wave tables, plus one sound-effect channel that borrows a SID voice while
; an effect sounds and hands it back when the effect is over (the music
; voice keeps sequencing silently underneath, so it comes back in time).
; Per-instrument: ADSR, a wave table (waveform + relative/absolute pitch per
; step: arpeggios, drums, pitch sweeps), pulse-width modulation, delayed
; vibrato. Per song: tempo, filter routing/mode and a cutoff sweep.
; Notes get a two-frame hard restart (gate off, ADSR zeroed) so every
; attack is clean.
;
; Pay-for-what-you-use: the whole file assembles to nothing unless the
; program calls one of the C64.Music methods.
;
; ---------------------------------------------------------------------------
; Interrupt hook
; ---------------------------------------------------------------------------
; Music_Tick is the player: one call = one tick. It is a plain subroutine
; (rts), touches NO zero page (pattern data is read through a self-modified
; absolute address), uses A/X/Y, and writes $D400-$D418.
;
; Music.Install() hooks it to the KERNAL's IRQ RAM vector ($0314/$0315):
; the vector's previous value becomes the operand of the `jmp` at
; music_irq_jmp, and the vector is pointed at music_irq, which is just
;       jsr Music_Tick
;       jmp <previous handler>      (normally $EA31, the KERNAL's own)
; So it rides the IRQ that is already there -- CIA1 timer A, which the
; KERNAL programs to 60 Hz on both PAL and NTSC machines -- and tempo is in
; 1/60 s ticks. Nothing is reprogrammed, the jiffy clock/keyboard scan keep
; running, and it chains in either order with C64.Interrupt (asm/C64.asm's
; C64_add_Interrupt saves and chains the vector the same way).
;
; A program that takes over interrupts itself (a raster IRQ, the CIA IRQ
; switched off) must not call Music.Install(); instead its own handler does
; `jsr Music_Tick` once per frame (from C#: C64.Music.Tick()). At 50 Hz
; everything is 5/6 of the speed -- lower the songs' tempo values to match.
; If a raster IRQ is added *alongside* the CIA IRQ on the same $0314 vector,
; only run the chain for the CIA source, or the player ticks twice.
;
; ---------------------------------------------------------------------------
; Data the program supplies (generated by tools/sidmusic.py -- see that
; file for the readable source format). All tables are indexed with an
; 8-bit register, so each is at most 256 bytes.
; ---------------------------------------------------------------------------
;   music_song_ord0/1/2  per song: each voice's start index in music_orders
;   music_song_tempo     per song: ticks per pattern row (>= 3)
;   music_song_filter    per song: $D417 (resonance << 4 | voice routing bits)
;   music_song_modevol   per song: $D418 (filter mode << 4 | volume)
;   music_song_cutmin/cutmax/cutspd  per song: $D416 sweeps min..max..min,
;                        moving one step every 256/cutspd ticks (0 = static)
;   music_orders         order lists: $00-$7F pattern number,
;                        $80-$FC transpose (value - $A0 semitones),
;                        $FD nn start song nn, $FE voice ends, $FF nn jump
;                        to order index nn
;   music_pat_lo/hi      pattern addresses. Pattern 0 must be a lone $FF.
;                        Pattern bytes: $00-$5F note (0 = C-0), $60 rest
;                        (gate off), $61 tie, $80-$BF row count 1..64 for
;                        the events that follow, $C0-$FE instrument
;                        (value - $C0), $FF end
;   music_ins_ad/sr      per instrument: SID attack/decay, sustain/release
;   music_ins_wave       index of its first wave table row
;   music_ins_wspd       ticks per wave table row
;   music_ins_pw         pulse width: bits 0-3 = high nibble ($D403),
;                        bits 4-7 = top of the low byte. High nibble 2..13.
;   music_ins_pws        pulse width change per tick (0 = fixed); it swings
;                        between $2xx and $Exx
;   music_ins_vspd       vibrato half period in ticks (0 = none); depth
;                        grows with it (about 7 cents per tick)
;   music_ins_vdly       ticks before the vibrato starts
;   music_wave_l/r       wave table rows. l: $00 keep the waveform, $FF
;                        jump to row r, else the $D404 value (gate bit set).
;                        r: $00-$7F semitones above the note, $80-$FF an
;                        absolute note (value - $80)
;   music_sfx_ins/note/len  per effect: instrument, note, length in ticks.
;                        A higher effect number wins over a lower one that
;                        is still sounding.
;   music_sfx_reg        (a symbol, not a table) SID register offset of the
;                        voice effects borrow: 0, 7 or 14
; ===========================================================================

.weak
Flag_Music_Install = 0
.endweak
.weak
Flag_Music_Play = 0
.endweak
.weak
Flag_Music_Stop = 0
.endweak
.weak
Flag_Music_PlayEffect = 0
.endweak
.weak
Flag_Music_Tick = 0
.endweak

.if Flag_Music_Install | Flag_Music_Play | Flag_Music_Stop | Flag_Music_PlayEffect | Flag_Music_Tick

MUSIC_REST = $60

; ---- player state (zeroed by music_reset) ---------------------------------
music_state
m_playing   .byte 0         ; nonzero while a song is being sequenced
m_chain     .byte 0         ; song number + 1 to start at the end of this tick
m_tempo     .byte 0
m_modevol   .byte 0
m_cut       .byte 0
m_cutfrac   .byte 0
m_cutdir    .byte 0
m_cutmin    .byte 0
m_cutmax    .byte 0
m_cutspd    .byte 0
m_sfx       .byte 0         ; number of the effect on the effect channel
m_flo       .byte 0
m_fhi       .byte 0
; Channels 0-2 are the music voices, channel 3 is the effect channel.
mv_count    .fill 4         ; ticks to the next event (3: ticks the effect has left, 0 = idle)
mv_pend     .fill 3         ; event fetched two ticks early, applied when mv_count hits 0
mv_dur      .fill 3         ; rows the pending event lasts
mv_ins      .fill 3
mv_trans    .fill 3
mv_ord      .fill 3         ; next index in music_orders
mv_pat      .fill 3         ; current pattern
mv_ppos     .fill 3         ; next byte in it
mv_note     .fill 4         ; note the wave table is relative to
mv_cur      .fill 4         ; note actually sounding
mv_wptr     .fill 4
mv_wcnt     .fill 4
mv_wspd     .fill 4
mv_wave     .fill 4         ; $D404 value...
mv_gate     .fill 4         ; ...ANDed with this ($FF, or $FE = gate off)
mv_ad       .fill 4
mv_sr       .fill 4
mv_pwlo     .fill 4
mv_pwhi     .fill 4
mv_pws      .fill 4
mv_pwdir    .fill 4
mv_vspd     .fill 4
mv_vcnt     .fill 4
mv_vdir     .fill 4
mv_vdly     .fill 4
mv_vlo      .fill 4         ; vibrato's offset from the note's frequency
mv_vhi      .fill 4
music_state_end

music_regofs .byte 0, 7, 14, music_sfx_reg

; PAL SID frequency values for C-0 .. B-7 (hz * 2^24 / 985248; B-7 is past
; the top of the register and clipped).
music_freq_lo
    .byte $16, $27, $39, $4b, $5f, $74, $8a, $a1, $ba, $d4, $f0, $0e
    .byte $2d, $4e, $71, $96, $be, $e7, $14, $42, $74, $a9, $e0, $1b
    .byte $5a, $9c, $e2, $2d, $7b, $cf, $27, $85, $e8, $51, $c1, $37
    .byte $b4, $38, $c4, $59, $f7, $9d, $4e, $0a, $d0, $a2, $81, $6d
    .byte $67, $70, $89, $b2, $ed, $3b, $9c, $13, $a0, $45, $02, $da
    .byte $ce, $e0, $11, $64, $da, $76, $39, $26, $40, $89, $04, $b4
    .byte $9c, $c0, $23, $c8, $b4, $eb, $72, $4c, $80, $12, $08, $68
    .byte $39, $80, $45, $90, $68, $d6, $e3, $99, $00, $24, $10, $ff
music_freq_hi
    .byte $01, $01, $01, $01, $01, $01, $01, $01, $01, $01, $01, $02
    .byte $02, $02, $02, $02, $02, $02, $03, $03, $03, $03, $03, $04
    .byte $04, $04, $04, $05, $05, $05, $06, $06, $06, $07, $07, $08
    .byte $08, $09, $09, $0a, $0a, $0b, $0c, $0d, $0d, $0e, $0f, $10
    .byte $11, $12, $13, $14, $15, $17, $18, $1a, $1b, $1d, $1f, $20
    .byte $22, $24, $27, $29, $2b, $2e, $31, $34, $37, $3a, $3e, $41
    .byte $45, $49, $4e, $52, $57, $5c, $62, $68, $6e, $75, $7c, $83
    .byte $8b, $93, $9c, $a5, $af, $b9, $c4, $d0, $dd, $ea, $f8, $ff

; ---------------------------------------------------------------------------
; C64.Music.Install() -- silence the SID, clear the player and hook the
; KERNAL IRQ vector (see the top of this file). Calling it again does
; nothing.
; ---------------------------------------------------------------------------
.if Flag_Music_Install
Music_Install
    lda music_irq_jmp+2         ; a handler address never has a zero high byte
    bne _done
    ldx #music_state_end - music_state
    ; (lda #0: A is already 0 here)
-   sta music_state-1,x
    dex
    bne -
    ldx #$18
-   sta $d400,x
    dex
    bpl -
    lda #$0f                    ; effects are audible before any song sets a volume
    sta m_modevol
    php
    sei
    lda $0314
    sta music_irq_jmp+1
    lda $0315
    sta music_irq_jmp+2
    lda #<music_irq
    sta $0314
    lda #>music_irq
    sta $0315
    plp
_done
    rts

music_irq
    jsr Music_Tick
music_irq_jmp
    jmp $0000                   ; operand = the handler that was there before
.endif

; ---------------------------------------------------------------------------
; C64.Music.Play(song)
; ---------------------------------------------------------------------------
.if Flag_Music_Play
Music_Play
    #stack_save_return_adress zp_tmp1_low
    #stack_pull_int_a
    php
    sei                         ; the tick must not see a half-initialised song
    jsr music_song_init
    plp
    #stack_return_to_saved_address zp_tmp1_low
.endif

; ---------------------------------------------------------------------------
; C64.Music.Stop() -- the song stops and its notes are released; effects
; still play.
; ---------------------------------------------------------------------------
.if Flag_Music_Stop
Music_Stop
    lda #0
    sta m_playing
    ldx #2
    lda #$fe
-   sta mv_gate,x
    dex
    bpl -
    rts
.endif

; ---------------------------------------------------------------------------
; C64.Music.PlayEffect(effect)
; ---------------------------------------------------------------------------
.if Flag_Music_PlayEffect
Music_PlayEffect
    #stack_save_return_adress zp_tmp1_low
    #stack_pull_int_y
    php
    sei
    lda mv_count+3
    beq +
    cpy m_sfx                   ; one is sounding: only an equal or higher number replaces it
    bcc _skip
+   sty m_sfx
    lda music_sfx_len,y
    sta mv_count+3
    lda music_sfx_note,y
    pha
    lda music_sfx_ins,y
    tay
    pla
    ldx #3
    jsr music_note_init
_skip
    plp
    #stack_return_to_saved_address zp_tmp1_low
.endif

; Starts song A. Interrupts must be off (or this is the tick itself).
music_song_init
    tay
    lda music_song_ord0,y
    sta mv_ord
    lda music_song_ord1,y
    sta mv_ord+1
    lda music_song_ord2,y
    sta mv_ord+2
    lda music_song_tempo,y
    sta m_tempo
    lda music_song_filter,y
    sta $d417
    lda music_song_modevol,y
    sta m_modevol
    lda music_song_cutmax,y
    sta m_cutmax
    lda music_song_cutspd,y
    sta m_cutspd
    lda music_song_cutmin,y
    sta m_cutmin
    sta m_cut
    ldx #2
-   lda #0
    sta mv_pat,x                ; pattern 0 is empty, so the first fetch
    sta mv_ppos,x               ; goes straight to the order list
    sta mv_trans,x
    sta mv_ins,x
    lda #MUSIC_REST
    sta mv_pend,x
    lda #$fe
    sta mv_gate,x               ; release whatever the previous song left sounding
    lda #1
    sta mv_dur,x
    lda #3
    sta mv_count,x
    dex
    bpl -
    stx m_playing               ; $ff
    inx
    stx m_cutdir
    stx m_chain
    rts

; Starts note A with instrument Y on channel X.
music_note_init
    sta mv_note,x
    lda music_ins_ad,y
    sta mv_ad,x
    lda music_ins_sr,y
    sta mv_sr,x
    lda music_ins_wave,y
    sta mv_wptr,x
    lda music_ins_wspd,y
    sta mv_wspd,x
    lda #1
    sta mv_wcnt,x               ; the first wave table row runs this very tick
    lda music_ins_pws,y
    sta mv_pws,x
    beq +
    lda mv_pwhi,x               ; a modulated pulse carries on from wherever the
    bne ++                      ; channel's pulse width already is
+   lda music_ins_pw,y
    sta mv_pwlo,x
    and #$0f
    sta mv_pwhi,x
+   lda music_ins_vdly,y
    sta mv_vdly,x
    lda music_ins_vspd,y
    sta mv_vspd,x
    lsr                         ; start a quarter period in, so the swing is
    adc #0                      ; centred on the note
    sta mv_vcnt,x
    lda #0
    sta mv_vlo,x
    sta mv_vhi,x
    sta mv_vdir,x
    lda #$ff
    sta mv_gate,x
    rts

; ---------------------------------------------------------------------------
; C64.Music.Tick() -- one player tick. See the top of this file.
; ---------------------------------------------------------------------------
Music_Tick
    lda m_modevol
    sta $d418

    ; filter cutoff sweep
    lda m_cutspd
    beq _cutdone
    clc
    adc m_cutfrac
    sta m_cutfrac
    bcc _cutdone
    lda m_cutdir
    bne _cutdown
    inc m_cut
    lda m_cut
    cmp m_cutmax
    bcc _cutdone
    inc m_cutdir
    bne _cutdone
_cutdown
    dec m_cut
    lda m_cutmin
    cmp m_cut
    bcc _cutdone
    dec m_cutdir
_cutdone
    lda m_cut
    sta $d416

    ldx #2
_voice
    lda m_playing
    beq _chan
    dec mv_count,x
    bne _early
    ; the pending event starts now
    lda mv_pend,x
    cmp #MUSIC_REST
    bcc _noteon
    bne _setcount               ; tie: nothing changes
    lda #$fe                    ; rest: gate off
    sta mv_gate,x
    bne _setcount
_noteon
    ldy mv_ins,x
    jsr music_note_init
_setcount
    lda #0
    ldy mv_dur,x
-   clc
    adc m_tempo
    dey
    bne -
    sta mv_count,x
    bne _chan
_early
    lda mv_count,x
    cmp #2                      ; two ticks ahead: fetch the next event, and
    bne _chan                   ; hard-restart the voice if it is a note
    jsr music_fetch
_chan
    jsr music_chan
    dex
    bpl _voice

    ldx #3
    lda mv_count+3
    beq +
    jsr music_chan
    dec mv_count+3
+
    ldy m_chain
    beq +
    dey
    tya
    jmp music_song_init
+   rts

; Reads voice X's next event into mv_pend (following pattern ends, order
; list commands, instrument and length changes on the way).
music_fetch
_next
    ldy mv_pat,x
    lda music_pat_lo,y
    sta _read+1
    lda music_pat_hi,y
    sta _read+2
    ldy mv_ppos,x
    inc mv_ppos,x
_read
    lda $ffff,y
    cmp #$c0
    bcs _high
    cmp #$80
    bcs _length
    cmp #MUSIC_REST
    bcs _store
    clc
    adc mv_trans,x
    pha
    lda #$fe                    ; hard restart: gate off and ADSR zeroed for
    sta mv_gate,x               ; the two ticks before the note
    lda #0
    sta mv_ad,x
    sta mv_sr,x
    pla
_store
    sta mv_pend,x
    rts
_length
    and #$3f
    adc #0                      ; carry is set: +1
    sta mv_dur,x
    bne _next
_high
    cmp #$ff
    beq _patend
    sbc #$bf                    ; carry is clear: A - $c0
    sta mv_ins,x
    bcs _next
_patend
    ldy mv_ord,x
_order
    lda music_orders,y
    iny
    cmp #$80
    bcc _pattern
    cmp #$fd
    bcs _command
    sbc #$9f                    ; carry is clear: A - $a0
    sta mv_trans,x
    jmp _order
_command
    beq _songchain              ; $fd
    cmp #$ff
    beq _jump
    lda #MUSIC_REST             ; $fe: this voice is done, and stays here
    bne _store
_jump
    lda music_orders,y
    tay
    bcs _order                  ; carry is set by the cmp #$ff
_songchain
    lda music_orders,y
    clc
    adc #1
    sta m_chain
    lda #MUSIC_REST
    bne _store
_pattern
    sta mv_pat,x
    tya
    sta mv_ord,x
    lda #0
    sta mv_ppos,x
    beq _next

; One tick of channel X's sound: wave table, vibrato, pulse width, then the
; SID registers (unless an effect currently owns this music voice).
music_chan
    dec mv_wcnt,x
    bne _wavedone
    lda mv_wspd,x
    sta mv_wcnt,x
    ldy mv_wptr,x
_row
    lda music_wave_l,y
    beq _pitch                  ; $00: waveform unchanged
    cmp #$ff
    bne _setwave
    lda music_wave_r,y          ; $ff: jump (never to another jump)
    tay
    bcs _row
_setwave
    sta mv_wave,x
_pitch
    lda music_wave_r,y
    bpl _relative
    and #$7f
    bpl _setnote
_relative
    clc
    adc mv_note,x
_setnote
    sta mv_cur,x
    iny
    tya
    sta mv_wptr,x
_wavedone

    lda mv_vspd,x
    beq _vibdone
    lda mv_vdly,x
    beq _vibrate
    dec mv_vdly,x
    bpl _vibdone
_vibrate
    ldy mv_cur,x                ; step = frequency / 256, about 7 cents
    lda mv_vdir,x
    bne _vibdown
    clc
    lda mv_vlo,x
    adc music_freq_hi,y
    sta mv_vlo,x
    bcc _vibcount
    inc mv_vhi,x
    bcs _vibcount
_vibdown
    sec
    lda mv_vlo,x
    sbc music_freq_hi,y
    sta mv_vlo,x
    bcs _vibcount
    dec mv_vhi,x
_vibcount
    dec mv_vcnt,x
    bne _vibdone
    lda mv_vspd,x
    sta mv_vcnt,x
    lda mv_vdir,x
    eor #1
    sta mv_vdir,x
_vibdone

    lda mv_pws,x
    beq _pwdone
    lda mv_pwdir,x
    bne _pwdown
    clc
    lda mv_pwlo,x
    adc mv_pws,x
    sta mv_pwlo,x
    bcc +
    inc mv_pwhi,x
+   lda mv_pwhi,x
    cmp #$0e
    bcc _pwdone
    inc mv_pwdir,x
    bne _pwdone
_pwdown
    sec
    lda mv_pwlo,x
    sbc mv_pws,x
    sta mv_pwlo,x
    bcs +
    dec mv_pwhi,x
+   lda mv_pwhi,x
    cmp #$02
    bcs _pwdone
    dec mv_pwdir,x
_pwdone

    ldy mv_cur,x
    clc
    lda music_freq_lo,y
    adc mv_vlo,x
    sta m_flo
    lda music_freq_hi,y
    adc mv_vhi,x
    sta m_fhi

    ldy music_regofs,x
    cpx #3
    beq _write
    lda mv_count+3              ; a music voice: silent while an effect has
    beq _write                  ; borrowed its SID voice
    cpy music_regofs+3
    beq _skip
_write
    lda m_flo
    sta $d400,y
    lda m_fhi
    sta $d401,y
    lda mv_pwlo,x
    sta $d402,y
    lda mv_pwhi,x
    sta $d403,y
    lda mv_ad,x
    sta $d405,y
    lda mv_sr,x
    sta $d406,y
    lda mv_wave,x
    and mv_gate,x
    sta $d404,y
_skip
    rts

.endif
