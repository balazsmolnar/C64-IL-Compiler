; Starts song A. Interrupts must be off (or this is the tick itself).
music_song_init
    tay
    lda music_song_ord0,y
    sta mv_ord
    lda music_song_ord1,y
    sta mv_ord+1
    lda music_song_ord2,y
    sta mv_ord+2
    lda music_song_tempo,y
    sta m_tempo
    lda music_song_res,y
    sta m_res
    lda music_song_modevol,y
    sta m_modevol
    lda music_song_cutmax,y
    sta m_cutmax
    sta m_cut                   ; open until an instrument sets it
    lda music_song_cutmin,y
    sta m_cutmin
    ldx #2
-   lda #0
    sta mv_pat,x                ; pattern 0 is empty, so the first fetch
    sta mv_ppos,x               ; goes straight to the order list
    sta mv_trans,x
    sta mv_ins,x
    lda #MUSIC_REST
    sta mv_pend,x
    lda #$fe
    sta mv_gate,x               ; release whatever the previous song left sounding
    lda #1
    sta mv_dur,x
    lda #3
    sta mv_count,x
    dex
    bpl -
    stx m_playing               ; $ff
    inx
    stx m_chain
    stx m_cutd
    stx m_route
    rts

; Starts note A with instrument Y on channel X.
music_note_init
    sta mv_note,x
    lda music_ins_ad,y
    sta mv_ad,x
    lda music_ins_sr,y
    sta mv_sr,x
    lda music_ins_wave,y
    sta mv_wptr,x
    lda music_ins_wspd,y
    sta mv_wspd,x
    lda #1
    sta mv_wcnt,x               ; the first wave table row runs this very tick
    lda music_ins_pws,y
    sta mv_pws,x
    beq +
    cpx #3                      ; an effect always starts from its own pulse width;
    beq +                       ; a modulated music voice carries on from wherever
    lda mv_pwhi,x               ; its pulse width already is
    bne ++
+   lda music_ins_pw,y
    sta mv_pwlo,x
    and #$0f
    sta mv_pwhi,x
+   lda music_ins_vdly,y
    sta mv_vdly,x
    lda music_ins_vspd,y
    sta mv_vspd,x
    lsr                         ; start a quarter period in, so the swing is
    adc #0                      ; centred on the note
    sta mv_vcnt,x
    lda music_ins_sllo,y
    sta mv_sllo,x
    lda music_ins_slhi,y
    sta mv_slhi,x
    lda music_ins_gate,y
    and #$7f
    sta mv_goff,x
    tya
    sta mv_lins,x
    cpx #3                      ; the effect channel has its own routing bit and
    bne _music                  ; never touches the music's cutoff
    lda music_ins_filt,y
    beq +
    lda #music_sfx_bit
+   sta m_fxroute
    jmp _unfiltered
_music
    lda music_regbit,x          ; filter routing and cutoff envelope
    eor #$ff
    and m_route
    sta m_route
    lda music_ins_filt,y
    beq _unfiltered
    cmp #$ff
    beq +
    sta m_cut
    lda music_ins_fdel,y
    sta m_cutd
+   lda m_route
    ora music_regbit,x
    sta m_route
_unfiltered
    lda #0
    sta mv_vlo,x
    sta mv_vhi,x
    sta mv_vdir,x
    lda #$ff
    sta mv_gate,x
    rts

; ---------------------------------------------------------------------------
; C64.Music.Tick() -- one player tick. See the top of this file.
; ---------------------------------------------------------------------------
Music_Tick
    lda m_modevol
    sta $d418
    inc m_frame
    lda m_route
    ldy mv_count+3
    beq +
    and #~music_sfx_bit & $ff   ; while an effect sounds, its routing bit, not the music's
    ora m_fxroute
+   ora m_res
    sta $d417

    ; filter cutoff envelope
    lda m_cutd
    beq _cutdone
    bmi _cutdown
    clc
    adc m_cut
    bcs _cutmax
    cmp m_cutmax
    bcc _cutset
_cutmax
    lda m_cutmax
    jmp _cutset
_cutdown
    clc
    adc m_cut
    bcc _cutmin
    cmp m_cutmin
    bcs _cutset
_cutmin
    lda m_cutmin
_cutset
    sta m_cut
_cutdone
    lda m_cut
    sta $d416

    ldx #2
_voice
    lda m_playing
    beq _chan
    dec mv_count,x
    bne _early
    ; the pending event starts now
    lda mv_pend,x
    cmp #MUSIC_REST
    bcc _noteon
    bne _setcount               ; tie: nothing changes
    lda #$fe                    ; rest: gate off
    sta mv_gate,x
    bne _setcount
_noteon
    ldy mv_ins,x
    jsr music_note_init
_setcount
    lda #0
    ldy mv_dur,x
-   clc
    adc m_tempo
    dey
    bne -
    sta mv_count,x
    bne _chan
_early
    lda mv_count,x
    cmp #2                      ; two ticks ahead: fetch the next event, and
    bne _chan                   ; hard-restart the voice if it is a note
    jsr music_fetch
_chan
    jsr music_chan
    dex
    bpl _voice

    ; the effect channel
    lda mv_count+3
    beq _sfxdone
    ldy #music_sfx_reg
    lda m_sfxhr
    beq +
    lda #0                      ; the tick before an effect: test bit on, gate
    sta m_sfxhr                 ; off, ADSR zero -- whatever the voice was doing,
    sta $d405,y                 ; its envelope is at nothing when the effect starts
    sta $d406,y
    beq _gateoff
+   ldx #3
    jsr music_chan
    dec mv_count+3
    bne _sfxdone
    ldy #music_sfx_reg          ; over: gate off, so the music's own note on this
_gateoff                        ; voice gets a fresh attack when it comes back
    lda #$08
    sta $d404,y
_sfxdone

    ldy m_chain
    beq _done
.if MUSIC_RESUMABLE
    iny
    beq music_restore           ; $fd $fe
    dey
.endif
    dey
    tya
    jmp music_song_init
_done
    rts

; Reads voice X's next event into mv_pend (following pattern ends, order
; list commands, instrument and length changes on the way).
music_fetch
_next
    ldy mv_pat,x
    lda music_pat_lo,y
    sta _read+1
    lda music_pat_hi,y
    sta _read+2
    ldy mv_ppos,x
    inc mv_ppos,x
_read
    lda $ffff,y
    cmp #$c0
    bcs _high
    cmp #$80
    bcs _length
    cmp #MUSIC_REST
    bcs _store
    clc
    adc mv_trans,x
    sta mv_pend,x
    ldy mv_ins,x
    lda music_ins_gate,y
    bpl +
    tya                         ; legato, and the same instrument is sounding:
    cmp mv_lins,x               ; no hard restart
    beq _done
+   lda #$fe                    ; hard restart: gate off and ADSR zeroed for
    sta mv_gate,x               ; the two ticks before the note
    lda #0
    sta mv_ad,x
    sta mv_sr,x
_done
    rts
_store
    sta mv_pend,x
    rts
_length
    and #$3f
    adc #0                      ; carry is set: +1
    sta mv_dur,x
    bne _next
_high
    cmp #$ff
    beq _patend
    sbc #$bf                    ; carry is clear: A - $c0
    sta mv_ins,x
    bcs _next
_patend
    ldy mv_ord,x
_order
    lda music_orders,y
    iny
    cmp #$80
    bcc _pattern
    cmp #$fd
    bcs _command
    sbc #$9f                    ; carry is clear: A - $a0
    sta mv_trans,x
    jmp _order
_command
    beq _songchain              ; $fd
    cmp #$ff
    beq _jump
    lda #MUSIC_REST             ; $fe: this voice is done, and stays here
    bne _store
_jump
    lda music_orders,y
    tay
    bcs _order                  ; carry is set by the cmp #$ff
_songchain
    lda music_orders,y
    clc
    adc #1
    sta m_chain
    lda #MUSIC_REST
    bne _store
_pattern
    sta mv_pat,x
    tya
    sta mv_ord,x
    lda #0
    sta mv_ppos,x
    beq _next

; One tick of channel X's sound: early gate-off, wave table, vibrato, slide,
; pulse width, then the SID registers (unless an effect currently owns this
; music voice).
music_chan
    lda mv_count,x
    cmp mv_goff,x
    bne +
    lda #$fe
    sta mv_gate,x
+
    dec mv_wcnt,x
    bne _wavedone
    lda mv_wspd,x
    sta mv_wcnt,x
    ldy mv_wptr,x
_row
    lda music_wave_l,y
    beq _pitch                  ; $00: waveform unchanged
    cmp #$ff
    bne _setwave
    lda music_wave_r,y          ; $ff: jump (never to another jump)
    tay
    bcs _row
_setwave
    sta mv_wave,x
_pitch
    lda music_wave_r,y
    bpl _relative
    and #$7f
    bpl _setnote
_relative
    clc
    adc mv_note,x
_setnote
    sta mv_cur,x
    iny
    tya
    sta mv_wptr,x
_wavedone

    lda mv_vspd,x
    beq _vibdone
    lda mv_vdly,x
    beq _vibrate
    dec mv_vdly,x
    bpl _vibdone
_vibrate
    ldy mv_cur,x                ; step = frequency / 256, about 7 cents
    jsr music_freq
    lda mv_vdir,x
    bne _vibdown
    clc
    lda mv_vlo,x
    adc m_fhi
    sta mv_vlo,x
    bcc _vibcount
    inc mv_vhi,x
    bcs _vibcount
_vibdown
    sec
    lda mv_vlo,x
    sbc m_fhi
    sta mv_vlo,x
    bcs _vibcount
    dec mv_vhi,x
_vibcount
    dec mv_vcnt,x
    bne _vibdone
    lda mv_vspd,x
    sta mv_vcnt,x
    lda mv_vdir,x
    eor #1
    sta mv_vdir,x
_vibdone

    clc                         ; slide
    lda mv_vlo,x
    adc mv_sllo,x
    sta mv_vlo,x
    lda mv_vhi,x
    adc mv_slhi,x
    sta mv_vhi,x

    lda mv_pws,x
    beq _pwdone
    lda mv_pwdir,x
    bne _pwdown
    clc
    lda mv_pwlo,x
    adc mv_pws,x
    sta mv_pwlo,x
    bcc +
    inc mv_pwhi,x
+   lda mv_pwhi,x
    cmp #$0e
    bcc _pwdone
    inc mv_pwdir,x
    bne _pwdone
_pwdown
    sec
    lda mv_pwlo,x
    sbc mv_pws,x
    sta mv_pwlo,x
    bcs +
    dec mv_pwhi,x
+   lda mv_pwhi,x
    cmp #$02
    bcs _pwdone
    dec mv_pwdir,x
_pwdone

    ldy mv_cur,x
    jsr music_freq
    clc
    lda m_flo
    adc mv_vlo,x
    sta m_flo
    lda m_fhi
    adc mv_vhi,x
    sta m_fhi

    ldy music_regofs,x
    cpx #3
    beq _write
    lda mv_count+3              ; a music voice: silent while an effect has
    beq _write                  ; borrowed its SID voice
    cpy #music_sfx_reg
    beq _skip
_write
    lda m_flo
    sta $d400,y
    lda m_fhi
    sta $d401,y
    lda mv_pwlo,x
    sta $d402,y
    lda mv_pwhi,x
    sta $d403,y
    lda mv_ad,x
    sta $d405,y
    lda mv_sr,x
    cpx #3
    bcs _sr
    pha                         ; a music voice while an effect sounds: ducked,
    lda mv_count+3              ; its sustain 4 steps lower (the envelope falls to
    beq _full                   ; it; it comes back with the voice's next note)
    pla
    sec
    sbc #$40
    bcs _sr
    and #$0f
    bcc _sr
_full
    pla
_sr
    sta $d406,y
    lda mv_wave,x
    and mv_gate,x
    sta $d404,y
_skip
    rts

.endif
