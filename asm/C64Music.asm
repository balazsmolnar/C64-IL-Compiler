; ===========================================================================
; C64.Music (C64Lib/Music.cs) -- a small data-driven SID music + sound
; effect player.
;
; Three music voices driven by order lists -> patterns -> instruments ->
; wave tables, plus one sound-effect channel that borrows a SID voice while
; an effect sounds and hands it back when the effect is over (the music
; voice keeps sequencing silently underneath, so it comes back in time, and
; its note is re-attacked).
; Per instrument: ADSR, a wave table (waveform + relative/absolute pitch per
; step: arpeggios, drums, ring modulation/sync, re-gating), pulse-width
; modulation, delayed vibrato, pitch slide, early gate-off (staccato) or no
; re-attack at all (legato), and a filter cutoff envelope.
; Notes get a two-tick hard restart (gate off, ADSR zeroed) so every attack
; is clean; effects get a one-tick one.
;
; Pay-for-what-you-use: the whole file assembles to nothing unless the
; program calls one of the C64.Music methods.
;
; ---------------------------------------------------------------------------
; Interrupt hook and tempo
; ---------------------------------------------------------------------------
; Music_Tick is the player: one call = one tick. It is a plain subroutine
; (rts), touches NO zero page (pattern data is read through a self-modified
; absolute address), uses A/X/Y, and writes $D400-$D418.
;
; A tick is one PAL video frame: 19656 cycles, 50.12 Hz. Tempo values are
; in ticks.
;
; Music.Install() hooks the tick to the KERNAL's IRQ RAM vector
; ($0314/$0315): the vector's previous value becomes the operand of the
; `jmp` at music_irq_jmp, and the vector is pointed at music_irq, which is
;       jsr Music_Tick
;       jmp <previous handler>      (normally $EA31, the KERNAL's own)
; It also re-times the interrupt that is already there: CIA 1 timer A (the
; KERNAL's 60 Hz jiffy/keyboard interrupt) is reloaded with 19656 cycles
; and restarted when the raster beam is at line 252. From then on the
; system interrupt comes once per frame, always in the bottom border just
; after line 251 -- so it can never hide line 251 from
; Screen.WaitForVBlank's polling (a 60 Hz interrupt drifting through the
; frame does, every few frames, and each time costs the main loop a whole
; frame). Side effect: the KERNAL jiffy clock ($A0-$A2, C64.Delay) counts
; 50ths of a second from then on.
;
; Screen.SetSplit (asm/C64Graphics.asm) turns the CIA interrupt off and
; calls the $0314 chain from its own raster interrupt, also once per frame
; at line 252: the player keeps exactly the same tempo with a split on or
; off, and Install/SetSplit can come in either order. It chains in either
; order with C64.Interrupt too.
;
; A program that takes over interrupts completely must not call
; Music.Install(); instead its own handler does `jsr Music_Tick` once per
; frame (from C#: C64.Music.Tick()).
;
; NTSC: the timer value and the frequency table are PAL. On an NTSC machine
; the music is a little fast and sharp and the interrupt is not frame
; locked.
;
; ---------------------------------------------------------------------------
; Data the program supplies (generated by tools/sidmusic.py -- see that
; file for the readable source format). All tables are indexed with an
; 8-bit register, so each is at most 256 bytes.
; ---------------------------------------------------------------------------
;   music_song_ord0/1/2  per song: each voice's start index in music_orders
;   music_song_tempo     per song: ticks per pattern row (>= 3)
;   music_song_res       per song: filter resonance << 4 (the low nibble of
;                        $D417, voice routing, comes from the instruments)
;   music_song_modevol   per song: $D418 (filter mode << 4 | volume)
;   music_song_cutmin/cutmax  per song: the range $D416 is kept in
;   music_orders         order lists: $00-$7F pattern number,
;                        $80-$FC transpose (value - $A0 semitones),
;                        $FD nn start song nn ($FE = resume the song that
;                        Music.Interrupt put aside), $FE voice ends,
;                        $FF nn jump to order index nn
;   music_pat_lo/hi      pattern addresses. Pattern 0 must be a lone $FF.
;                        Pattern bytes: $00-$5F note (0 = C-0), $60 rest
;                        (gate off), $61 tie, $80-$BF row count 1..64 for
;                        the events that follow, $C0-$FE instrument
;                        (value - $C0), $FF end
;   music_ins_ad/sr      per instrument: SID attack/decay, sustain/release
;   music_ins_wave       index of its first wave table row
;   music_ins_wspd       ticks per wave table row
;   music_ins_pw         pulse width: bits 0-3 = high nibble ($D403),
;                        bits 4-7 = top of the low byte. High nibble 2..13.
;   music_ins_pws        pulse width change per tick (0 = fixed); it swings
;                        between $2xx and $Exx
;   music_ins_vspd       vibrato half period in ticks (0 = none); depth
;                        grows with it (about 7 cents per tick)
;   music_ins_vdly       ticks before the vibrato starts
;   music_ins_sllo/slhi  pitch slide: signed 16-bit change of the SID
;                        frequency value per tick
;   music_ins_gate       bit 7: legato -- no hard restart, the note just
;                        changes pitch if the gate is already on.
;                        bits 0-6: gate off this many ticks before the end
;                        of the note/effect (0 = not at all)
;   music_ins_filt       0: voice not filtered. $FF: filtered, cutoff left
;                        as it is. Else: filtered, and each note sets the
;                        cutoff ($D416) to this value...
;   music_ins_fdel       ...then adds this (signed) to it every tick
;   music_wave_l/r       wave table rows. l: $00 keep the waveform, $FF
;                        jump to row r, else the $D404 value (gate bit set;
;                        a row with it clear followed by one with it set
;                        re-attacks the note).
;                        r: $00-$7F semitones above the note, $80-$FF an
;                        absolute note (value - $80)
;   music_sfx_ins/note/len  per effect: instrument, note, length in ticks.
;                        A higher effect number wins over a lower one that
;                        is still sounding.
;   music_sfx_reg        (symbols, not tables) SID register offset of the
;   music_sfx_bit        voice effects borrow (0, 7 or 14) and its $D417
;                        routing bit (1, 2 or 4)
; ===========================================================================

