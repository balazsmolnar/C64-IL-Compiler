MUSIC_REST = $60
MUSIC_FRAME_CYCLES = 19656          ; one PAL frame (312 lines * 63 cycles)

; ---- the song's state: what Music.Interrupt puts aside ---------------------
music_state
m_playing   .byte 0         ; nonzero while a song is being sequenced
m_chain     .byte 0         ; song number + 1 to start at the end of this tick
m_tempo     .byte 0
m_modevol   .byte 0
m_res       .byte 0
m_route     .byte 0         ; $D417's voice routing bits
m_cut       .byte 0
m_cutd      .byte 0         ; change of m_cut per tick
m_cutmin    .byte 0
m_cutmax    .byte 0
; Channels 0-2 are the music voices, channel 3 is the effect channel.
mv_count    .fill 4         ; ticks to the next event (3: ticks the effect has left, 0 = idle)
mv_pend     .fill 3         ; event fetched two ticks early, applied when mv_count hits 0
mv_dur      .fill 3         ; rows the pending event lasts
mv_ins      .fill 3
mv_lins     .fill 4         ; instrument of the note sounding now (legato needs the same one)
mv_trans    .fill 3
mv_ord      .fill 3         ; next index in music_orders
mv_pat      .fill 3         ; current pattern
mv_ppos     .fill 3         ; next byte in it
mv_note     .fill 4         ; note the wave table is relative to
mv_cur      .fill 4         ; note actually sounding
mv_wptr     .fill 4
mv_wcnt     .fill 4
mv_wspd     .fill 4
mv_wave     .fill 4         ; $D404 value...
mv_gate     .fill 4         ; ...ANDed with this ($FF, or $FE = gate off)
mv_goff     .fill 4         ; gate goes off when mv_count reaches this
mv_ad       .fill 4
mv_sr       .fill 4
mv_pwlo     .fill 4
mv_pwhi     .fill 4
mv_pws      .fill 4
mv_pwdir    .fill 4
mv_vspd     .fill 4
mv_vcnt     .fill 4
mv_vdir     .fill 4
mv_vdly     .fill 4
mv_vlo      .fill 4         ; offset from the note's frequency: vibrato + slide
mv_vhi      .fill 4
mv_sllo     .fill 4
mv_slhi     .fill 4
music_state_end
; ---- the rest of the player's variables ------------------------------------
m_sfx       .byte 0         ; number of the effect on the effect channel
m_sfxhr     .byte 0         ; nonzero: the effect starts next tick, this one kills the voice
m_fxroute   .byte 0         ; the effect's own $D417 routing bit (0 or music_sfx_bit)
m_frame     .byte 0         ; counts ticks (C64.Music.Frame)
m_saved     .byte 0         ; nonzero: music_save holds an interrupted song
m_flo       .byte 0
m_fhi       .byte 0
m_oct       .byte 0
music_vars_end
.if MUSIC_RESUMABLE
music_save  .fill music_state_end - music_state
.endif

music_regofs .byte 0, 7, 14, music_sfx_reg
music_regbit .byte 1, 2, 4, music_sfx_bit

; PAL SID frequency values for octave 6, C-6 .. B-6 (hz * 2^24 / 985248).
; Lower octaves are these halved (music_freq), octave 7 doubled (the LSB is
; lost there; B-7 is past the top of the register and clipped).
music_f6_lo
    .byte $9c, $c0, $23, $c8, $b4, $eb, $72, $4c, $80, $12, $08, $68
music_f6_hi
    .byte $45, $49, $4e, $52, $57, $5c, $62, $68, $6e, $75, $7c, $83

; Frequency of note Y (0 = C-0 .. 95) -> m_flo/m_fhi. Destroys A and Y.
music_freq
    tya
    ldy #$ff
    sec
-   iny                         ; Y = octave, A = semitone
    sbc #12
    bcs -
    adc #12
    sty m_oct
    tay
    lda music_f6_lo,y
    sta m_flo
    lda music_f6_hi,y
    sta m_fhi
    ldy m_oct
    cpy #7
    bne _down
    asl m_flo
    rol m_fhi
    bcc _done
    lda #$ff
    sta m_flo
    sta m_fhi
    rts
_down
    cpy #6
    beq _done
    lsr m_fhi
    ror m_flo
    iny
    bne _down
_done
    rts

; ---------------------------------------------------------------------------
; C64.Music.Install() -- silence the SID, clear the player, hook the
; KERNAL IRQ vector and lock the system interrupt to the video frame (see
; the top of this file). Calling it again does nothing.
; ---------------------------------------------------------------------------
.if Flag_Music_Install
Music_Install
    lda music_irq_jmp+2         ; a handler address never has a zero high byte
    bne _done
    ldx #music_vars_end - music_state
    ; (A is 0 here)
-   sta music_state-1,x
    dex
    bne -
    ldx #$18
-   sta $d400,x
    dex
    bpl -
    lda #$0f                    ; effects are audible before any song sets a volume
    sta m_modevol
    php
    sei
    lda $0314
    sta music_irq_jmp+1
    lda $0315
    sta music_irq_jmp+2
    lda #<music_irq
    sta $0314
    lda #>music_irq
    sta $0315
    lda #252                    ; lines 256-311 read 0-55 here, so this is line 252 itself
-   cmp $d012
    bne -
    lda #<(MUSIC_FRAME_CYCLES - 1)
    sta $dc04
    lda #>(MUSIC_FRAME_CYCLES - 1)
    sta $dc05
    lda $dc0e
    ora #%00010001              ; load the new period now, and (keep) running
    sta $dc0e
    plp
_done
    rts

music_irq
    jsr Music_Tick
music_irq_jmp
    jmp $0000                   ; operand = the handler that was there before
.endif

; ---------------------------------------------------------------------------
; C64.Music.Play(song) -- start a song from its beginning. Forgets a song
; put aside by Interrupt.
; ---------------------------------------------------------------------------
.if Flag_Music_Play
Music_Play
    #stack_save_return_adress zp_tmp1_low
    #stack_pull_int_a
    php
    sei                         ; the tick must not see a half-initialised song
    jsr music_song_init
    lda #0
    sta m_saved
    plp
    #stack_return_to_saved_address zp_tmp1_low
.endif

; ---------------------------------------------------------------------------
; C64.Music.Interrupt(song) -- put the playing song aside, exactly where it
; is, and play this one instead. If a song is already put aside, that one
; is kept and the current one is simply replaced.
; ---------------------------------------------------------------------------
.if Flag_Music_Interrupt
Music_Interrupt
    #stack_save_return_adress zp_tmp1_low
    #stack_pull_int_y
    php
    sei
    lda m_saved
    bne +
    inc m_saved
    ldx #music_state_end - music_state
-   lda music_state-1,x
    sta music_save-1,x
    dex
    bne -
+   tya
    jsr music_song_init
    plp
    #stack_return_to_saved_address zp_tmp1_low
.endif

; ---------------------------------------------------------------------------
; C64.Music.Resume() -- carry on with the song Interrupt put aside (nothing
; happens if there is none). Also what the order list command $FD $FE does.
; ---------------------------------------------------------------------------
.if Flag_Music_Resume
Music_Resume
    php
    sei
    jsr music_restore
    plp
    rts
.endif

.if MUSIC_RESUMABLE
music_restore
    lda m_saved
    beq _none
    ldx #music_state_end - music_state
-   lda music_save-1,x
    sta music_state-1,x
    dex
    bne -
    stx m_saved
    stx mv_count+3              ; the saved state's effect, if any, is long over
    lda #$08                    ; gates off, so every restored note is re-attacked
    sta $d404
    sta $d40b
    sta $d412
_none
    rts
.endif

