; C64.Music.Stop() -- the song stops and its notes are released; effects
; still play.
; ---------------------------------------------------------------------------
.if Flag_Music_Stop
Music_Stop
    lda #0
    sta m_playing
    ldx #2
    lda #$fe
-   sta mv_gate,x
    dex
    bpl -
    rts
.endif

